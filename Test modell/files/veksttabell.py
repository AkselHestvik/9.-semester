WEIGHTS = np.array([r[0] for r in _RAW], dtype=float)
SGR_TABLE = np.array([r[1] for r in _RAW], dtype=float)
FCR_TABLE = np.array([r[2] for r in _RAW], dtype=float)

def _wrow(w):
    return int(np.clip(np.searchsorted(WEIGHTS, w, side='right') - 1, 0, len(WEIGHTS)-1))

def sgr(w, T, interp_T=True):
    i = _wrow(w)
    if not interp_T:
        j = int(np.clip(np.searchsorted(TEMPS, T, side='right') - 1, 0, len(TEMPS)-1))
        return SGR_TABLE[i, j]
    Tc = np.clip(T, TEMPS[0], TEMPS[-1])
    return float(np.interp(Tc, TEMPS, SGR_TABLE[i]))

def fcr(w):
    return FCR_TABLE[_wrow(w)]

def grow(w0, T, days=30, kappa=1.0):
    w = float(w0)
    feed = 0.0
    for _ in range(days):
        dw = w * kappa * sgr(w, T) / 100.0
        feed += dw * fcr(w)
        w += dw
    return w, feed
